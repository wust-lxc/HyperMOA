"""Resolve historical paths while preserving the immutable initial migration."""

import hashlib
import json
import marshal
from pathlib import Path


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def migration(root):
    path = Path(root) / "benchmark/docs/layout_migration.json"
    return json.loads(path.read_text()) if path.exists() else {"moves": {}, "rewritten_files": {}}


def adjustments(root):
    path = Path(root) / "benchmark/docs/layout_adjustments.json"
    return json.loads(path.read_text()) if path.exists() else {}


def data_migration(root):
    path = Path(root) / "data/index/layout_migration.json"
    return json.loads(path.read_text()) if path.exists() else {}


def data_adjustments(root):
    path = Path(root) / "data/index/layout_adjustments.json"
    if not path.exists():
        return {}
    record = json.loads(path.read_text())
    if record["initial_migration_sha256"] != sha256(Path(root) / "data/index/layout_migration.json"):
        raise RuntimeError("Initial data migration audit changed")
    return record


def _mapped(relative, files, directories):
    if relative in files:
        return files[relative]
    for old, new in sorted(directories.items(), key=lambda item: -len(item[0])):
        if relative == old or relative.startswith(old + "/"):
            return new + relative[len(old):]
    return relative


def resolve_recorded_path(root, recorded):
    root = Path(root).resolve()
    path = Path(recorded)
    if path.is_absolute():
        try:
            relative = str(path.relative_to(root))
        except ValueError:
            return path
    else:
        relative = str(path)
    record = migration(root)
    directories = {**record.get("directory_moves", {}), **adjustments(root).get("directory_moves", {})}
    relative = _mapped(relative, record["moves"], directories)
    later = data_migration(root)
    relative = _mapped(relative, {**later.get("moves", {}), **later.get("duplicate_aliases", {})},
                       {**later.get("directory_moves", {}), **later.get("directory_aliases", {})})
    return root / relative


def verify_recorded_code(root, recorded, expected):
    resolved = resolve_recorded_path(root, recorded)
    actual = sha256(resolved)
    if actual == expected:
        return
    relative = str(resolved.relative_to(root))
    edges = []
    for record in (migration(root), data_migration(root)):
        for key, rewrite in record.get("rewritten_files", {}).items():
            if resolve_recorded_path(root, key) == resolved:
                edges.append((rewrite["source_sha256"], rewrite["current_sha256"]))
    for record in (adjustments(root), data_adjustments(root)):
        for key, update in record.get("updates", {}).items():
            if resolve_recorded_path(root, key) == resolved:
                edges.append((update["before_sha256"], update["after_sha256"]))
    reachable = {expected}
    for _ in range(len(edges)):
        reachable.update(after for before, after in edges if before in reachable)
    if actual in reachable:
        return
    raise RuntimeError(f"Recorded code changed outside the recorded layout migration: {recorded}")


def verify_protected_file(root, recorded, expected, protected):
    """Preserve data hashes; check migrated source and its regenerated bytecode."""
    path = resolve_recorded_path(root, recorded)
    if sha256(path) == expected:
        return
    if path.suffix == ".py":
        verify_recorded_code(root, recorded, expected)
        return
    if path.suffix == ".pyc" and path.parent.name == "__pycache__":
        old = Path(recorded)
        source = old.parent.parent / (old.name.split(".")[0] + ".py")
        expected_source = protected.get(str(source))
        if expected_source is None:
            raise RuntimeError(f"Regenerated cache has no protected source: {recorded}")
        verify_recorded_code(root, source, expected_source)
        current_source = resolve_recorded_path(root, source)
        cached_code = marshal.loads(path.read_bytes()[16:])
        compiled_code = compile(current_source.read_bytes(), str(current_source), "exec")
        if cached_code != compiled_code:
            raise RuntimeError(f"Regenerated cache does not match audited source: {recorded}")
        return
    raise RuntimeError(f"Protected scientific file changed: {recorded}")
